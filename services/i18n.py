def set_language(lang: str):
    global _LANG
    _LANG = "en" if lang == "en" else "fr"


def tr(key: str, *args) -> str:
    pair = T.get(key)
    if not pair:
        return key
    s = pair[1] if _LANG == "en" else pair[0]
    return s.format(*args) if args else s
